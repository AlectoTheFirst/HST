@pytest.mark.parametrize("version", VERSIONS)
def test_each_check_point_layer_has_one_qualified_package_and_both_cluster_members_enforce_it(version):
    graph = _graph(version)
    for code, (package, layer) in PACKAGES.items():
        props = graph.nodes[package].props
        assert "CpPolicyPackage" in graph.nodes[package].labels
        assert (props["authority_uid"], props["domain_uid"]) == ("cpmgmt-01", "smc")
        assert (props["management_release"], props["gateway_release"], props["api_version"]) == (
            "R81.20",
            "R81.20",
            "1.9",
        )
        assert props["capture_complete"] is True and props["implied_complete"] is True
        assert [node.uid for node in graph.sources(layer, "HAS_LAYER")] == [package]
        assert checkpoint_scope(graph, layer) == ("cpmgmt-01", "smc")
        assert graph.nodes[layer].props["match_context"] == "device"
        assert rule_explain._gateways(graph, layer) == [f"dev:{code}-cpfw-01"]
        assert [node.uid for node in graph.sources(layer, "ENFORCES")] == [f"dev:{code}-cpfw-01"]
        for gateway in rule_explain._gateways(graph, layer):
            policy, _context, checkpoint = rule_explain.rulebase_policy(graph, "test", layer, 4, gateway)
            assert checkpoint is True and policy is not None, (code, gateway)
            assert [item.uid for item in policy.layers] == [layer.removeprefix(f"{CP}:")]


