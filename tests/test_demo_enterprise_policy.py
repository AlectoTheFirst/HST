"""The firewall policy of the demo estate (fixtures/demo-enterprise) as the
symbolic engine reads it.

- The FortiGate rulebases are zone pairs (`match_context` zone-pair) and the
  corp-guest rulebases are access rulebases, so match_flow decides by the
  interfaces a flow enters and leaves by.
- vie01-guest-internet rule 3 (guest-https-legacy) is shadowed completely by
  rule 2 (guest-web).
- dc1-access and dc2-access belong to a qualified Check Point package written
  as the Check Point collector writes one, installed on both cluster members.

The files are generated by tools/gen_demo_enterprise.py, and the first test
checks that the committed files are the generator's output. The structural
tests read every version; the engine tests read v3 and need the native
backend.
"""

from __future__ import annotations

import importlib.util
import json
import os
from functools import cache
from ipaddress import ip_address
from pathlib import Path

import pytest
from tests.support.batch_inventory import inventory

from hst import symbolic
from hst.analysis_model.checkpoint_graph import checkpoint_scope
from hst.assessment import flow_match, rule_explain
from hst.core.fixtures import load_fixture

ROOT = Path(__file__).resolve().parent.parent
DEMO_DIR = ROOT / "fixtures" / "demo-enterprise"
VERSIONS = (1, 2, 3)
FGT = "dev:vie01-fgt-01"
FGID = "fgt:FGT100F7084444526:root"
GUEST_INTERNET = f"{FGID}:policy:guest-internet"
CORP_WAN = f"{FGID}:policy:corp-wan"
OFFICE_WEB = f"{FGID}:policy:6"
SHADOWED = f"{FGID}:policy:11"
CP = "cp:cpmgmt-01:smc"
PACKAGES = {
    "dc1": (f"{CP}:package:policy-dc1", f"{CP}:pkg-dc1-access"),
    "dc2": (f"{CP}:package:policy-dc2", f"{CP}:pkg-dc2-access"),
}


def _backend():
    if not symbolic.backend_available():
        if os.environ.get("HST_SYMBOLIC_REQUIRE") == "1":
            pytest.fail("required native backend missing")
        pytest.skip("optional native backend missing")


@cache
def _graph(version: int):
    return inventory(load_fixture(DEMO_DIR / f"estate-v{version}.yaml"))


def _flow(source: str, destination: str, port: int) -> dict:
    def point(text: str) -> list[list[int]]:
        return [[int(ip_address(text)), int(ip_address(text))]]

    return {
        "sources": point(source),
        "destinations": point(destination),
        "protocols": [6],
        "destination_ports": [[port, port]],
        "source_ports": None,
    }


def test_the_committed_files_are_the_generator_output(tmp_path, monkeypatch, capsys):
    spec = importlib.util.spec_from_file_location(
        "gen_demo_enterprise", ROOT / "tools" / "gen_demo_enterprise.py"
    )
    assert spec is not None and spec.loader is not None
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    monkeypatch.setattr(generator, "OUT", tmp_path)
    monkeypatch.setattr("sys.argv", ["gen_demo_enterprise.py"])

    generator.main()

    written = sorted(path.relative_to(tmp_path) for path in tmp_path.rglob("*.yaml"))
    assert [str(path) for path in written if path.parent == Path()] == [
        "estate-v1.yaml",
        "estate-v2.yaml",
        "estate-v3.yaml",
    ]
    for path in written:
        assert (tmp_path / path).read_bytes() == (DEMO_DIR / path).read_bytes(), path


# --- A1: zone pairs ------------------------------------------------------------------------------


@pytest.mark.parametrize("version", VERSIONS)
def test_every_fortigate_zone_pair_rulebase_says_so_and_corp_guest_is_an_access_rulebase(version):
    graph = _graph(version)
    zoned = [
        uid
        for uid in graph.labels["FwRulebase"]
        if graph.nodes[uid].props.get("vendor") == "fortinet"
        and graph.targets(uid, "FROM_ZONE")
        and graph.targets(uid, "TO_ZONE")
    ]

    assert zoned
    assert {graph.nodes[uid].props.get("match_context") for uid in zoned} == {"zone-pair"}
    corp_guest = [uid for uid in zoned if uid.endswith(":policy:corp-guest")]
    assert len(corp_guest) == len(zoned) // 5
    assert {graph.nodes[uid].props["kind"] for uid in corp_guest} == {"access"}


@pytest.mark.parametrize("version", VERSIONS)
def test_the_vienna_rulebases_receive_a_flow_by_its_interfaces(version):
    graph = _graph(version)
    names = {uid: graph.nodes[uid].props["name"] for uid in flow_match.device_rulebases(graph, FGT)}

    assert sorted(names.values()) == [
        "vie01-corp-guest",
        "vie01-corp-wan",
        "vie01-guest-corp",
        "vie01-guest-internet",
        "vie01-wan-corp",
    ]
    for ingress, receiving in (("port1", "vie01-corp-wan"), ("port2", "vie01-guest-internet")):
        received = {name for uid, name in names.items() if flow_match.receives(graph, uid, ingress, "port3")}
        assert received == {receiving}


def test_match_flow_decides_the_vienna_flow_by_the_zone_pair_it_enters_and_leaves_by():
    _backend()
    graph = _graph(3)
    flow = _flow("10.11.10.5", "8.8.8.8", 443)

    def entries(ingress: str) -> dict[str, dict]:
        document = flow_match.match(graph, "test", FGT, None, flow, 4, ingress=ingress, egress="port3")
        assert "error" not in document, document
        return {entry["name"]: entry for entry in document["rulebases"]}

    corp = entries("port1")
    assert corp["vie01-corp-wan"]["receives"] is True
    assert corp["vie01-corp-wan"]["decision"] == "permit"
    assert corp["vie01-corp-wan"]["deciding_rule"]["uid"] == OFFICE_WEB
    assert {name for name, entry in corp.items() if entry["decision"] != "not_applicable"} == {
        "vie01-corp-wan"
    }

    guest = entries("port2")
    assert guest["vie01-corp-wan"]["receives"] is False
    assert guest["vie01-corp-wan"]["decision"] == "not_applicable"
    assert guest["vie01-guest-internet"]["receives"] is True
    assert guest["vie01-guest-internet"]["decision"] == "deny"
    assert guest["vie01-guest-internet"]["deciding_rule"] is None
    assert {name for name, entry in guest.items() if entry["decision"] != "not_applicable"} == {
        "vie01-guest-internet"
    }


# --- A3: the shadowed rule -----------------------------------------------------------------------


@pytest.mark.parametrize("version", VERSIONS)
def test_guest_https_legacy_sits_at_position_3_and_guest_deny_rest_moves_to_4(version):
    graph = _graph(version)
    rules = sorted(
        (rule.props["position"], rule.props["name"], rule.uid)
        for rule in graph.targets(GUEST_INTERNET, "HAS_RULE")
    )

    assert rules == [
        (1, "guest-to-dns", f"{FGID}:policy:10"),
        (2, "guest-web", f"{FGID}:policy:2"),
        (3, "guest-https-legacy", SHADOWED),
        (4, "guest-deny-rest", f"{FGID}:policy:3"),
    ]
    props = graph.nodes[SHADOWED].props
    assert (props["action"], props["enabled"], props["rule_uid"]) == ("accept", True, "11")
    assert [node.uid for node in graph.targets(SHADOWED, "SRC")] == [f"{FGID}:addr:guest-net"]
    assert [node.uid for node in graph.targets(SHADOWED, "DST")] == [f"{FGID}:addr:internet"]
    assert [node.uid for node in graph.targets(SHADOWED, "SVC")] == [f"{FGID}:svc:HTTPS"]
    # the rule is added in Vienna only
    assert [
        uid for uid in graph.labels["FwRule"] if graph.nodes[uid].props.get("name") == "guest-https-legacy"
    ] == [SHADOWED]


def test_explain_rule_finds_no_flow_that_arrives_at_the_shadowed_rule():
    _backend()

    document = rule_explain.explain(_graph(3), "test", GUEST_INTERNET, SHADOWED, 4, limit=1000)

    assert "error" not in document, document
    assert document["entry"]["kind"] == "zone-pair" and document["entry"]["evaluated"] is True
    assert document["matches_nothing"] is False
    assert document["lower_empty"] is True and document["possible_empty"] is True
    assert document["definite_count"] == 0 and document["possible_count"] == 0
    assert document["summary"] == (
        "Earlier rules take every flow that rule 3 of vie01-guest-internet matches, so no flow arrives at it."
    )


